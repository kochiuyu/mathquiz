/* Home loader, tap targets, skip link, language hrefs and P5/P6 nav. */
const assert=require('assert').strict,fs=require('fs'),path=require('path'),vm=require('vm');
const root=path.join(__dirname,'..');
const read=f=>fs.readFileSync(path.join(root,f),'utf8');
const index=read('index.html');
assert(index.includes('href="?lang=en"')&&index.includes('href="?lang=zh"'),'language hrefs without JavaScript');
assert(index.includes('class="skip-link" href="#app"'),'static skip link');
assert(index.includes('Skip to content')&&index.includes('跳至內容'),'bilingual skip link');
const src=[...index.matchAll(/\ssrc="([^"]+)"/g)].map(m=>m[1]);
assert(src.at(-1).startsWith('learner-ui.js'),'learner ui stays last');
assert(src.includes('badges-ui.js?v=badges-v1'),'badges ui still a real script');
assert(src.includes('learner-catalog.js?v=p4-common-r1'),'catalog script stays');
assert(src.includes('ui.js?v=student-r1'),'student ui script stays');
assert(src.includes('answer-feedback.js?v=2'),'answer feedback script stays');
assert(!src.some(s=>s.startsWith('builder.js')),'builder is not on the student request list');
assert(!src.some(s=>s.startsWith('quiz.js')),'quiz is not on the student request list');
for(const token of ['builder.js?v=p6-core-r1','quiz.js?v=examples-r1','resources.js?v=p6-closure85-r1','pdf-export.js?v=p6-core-r1','number6.js?v=p6-core-r1','algebra6.js?v=p6-core-r1','measures6.js?v=p6-core-r1','shapes-data6.js?v=p6-core-r1','algebra5.js?v=all-core-p5-r1','measures5.js?v=measures-boolean-p5-r3','shapes-data5.js?v=all-core-p5-r1','fractions5.js?v=product-labels-r2','directions4.js?v=directions-r1','dissection4.js?v=dissect-r1','quadrilateral4.js?v=quad-r1','resource-browser.js?v=expanded-r1'])assert(index.includes(token),token);
assert(index.indexOf('src="learn-inquiry.js')<index.indexOf('src="learn.js'),'inquiry before learn');
assert(index.indexOf('learn-map.js')<index.indexOf('src="learn.js'),'map before learn');
assert(index.indexOf('learner-catalog.js?v=p4-common-r1')<index.indexOf('badges-data.js?v=badges-v1'),'catalog before badges');
const fn=index.match(/window\.mathQuizNeedsTeacher=function\(search,hash\)\{[\s\S]*?\n\};/);
assert(fn,'teacher predicate is present');
const ctx={window:{},URLSearchParams,URL};
vm.runInNewContext(fn[0],vm.createContext(ctx));
const needs=ctx.window.mathQuizNeedsTeacher;
assert.equal(needs('',''),false);
assert.equal(needs('?lang=zh&learner=1',''),false);
assert.equal(needs('?view=teacher',''),true);
assert.equal(needs('?view=build',''),true);
assert.equal(needs('?view=browse',''),true);
assert.equal(needs('?view=practice&p=1&skill=count20a',''),true);
assert.equal(needs('?v=3&p=1&items=&view=build',''),true);
assert.equal(needs('?v=4&p=6',''),true);
assert.equal(needs('?p=1',''),true);
assert.equal(needs('','#view=teacher'),true);
assert.equal(needs('','#library-results'),false);
const ui=read('learner-ui.js');
assert(ui.includes('p5-skill-levels.html')&&ui.includes('p6-skill-levels.html'),'P5 and P6 links');
assert(ui.includes('小五')&&ui.includes('小六'),'Chinese year names');
assert(ui.includes('My badges')&&ui.includes('我的徽章'));
assert(!ui.includes('localStorage')&&!ui.includes('sessionStorage'));
const badges=read('badges-ui.js');
assert(badges.includes('p5-skill-levels.html')&&badges.includes('p6-skill-levels.html'));
assert(badges.includes('三個級別都完成的課'));
assert(read('learner-ui.css').includes('.mqui-grades a{display:inline-flex')&&read('learner-ui.css').includes('min-height:44px'));
assert(read('learner-ui.css').includes('.mqui-language{display:inline-flex')&&read('learner-ui.css').includes('min-height:44px'));
assert(read('ui.css').includes('.skip-link:focus,.skip-link:focus-visible{position:static'));
assert(read('learn.css').includes('.learn-skip:focus,.learn-skip:focus-visible{position:static'));
assert(read('levels-ui.css').includes('.levels-hub{overflow-wrap:break-word;word-break:normal}'));
assert(!read('levels-ui.css').includes('word-break:break-all'));
assert(read('site-ui.js').includes('My badges')&&read('site-ui.js').includes('我的徽章'));
assert(read('p3-learn.js').includes('MathQuizBadges.sync(')&&!read('p3-learn.js').includes('handoff:true'));
assert(read('p4-learn.js').includes('MathQuizBadges.sync(')&&!read('p4-learn.js').includes('handoff:true'));
const siteCss=read('site-ui.css');
assert(siteCss.includes('@media(max-width:480px){.level-picker .level-options{grid-template-columns:1fr'),'level cards stack below 480px');
assert(siteCss.includes('.level-picker .level-option b{overflow-wrap:normal;word-break:normal'),'level subtitles do not break mid-word');
const learnCss=read('learn.css');
assert(learnCss.includes('.learn-path a,.learn-path-choices a,.learn-stages a,.learn-levels a,.foundation-route a,.learn-readiness a,.learn-inquiry a{display:inline-flex'),'lesson links keep a 44px target at every width');
assert(learnCss.includes('min-height:44px;min-width:44px'));
assert(!learnCss.includes('@media(max-width:700px){.learn-path h3 a'),'lesson target is not phone-only');
const learnerCss=read('learner-ui.css');
assert(learnerCss.includes('.mqui .route li>a,.mqui-context a,.mqui-topic-grid a,.mqui-connections a,.mqui-modes a'),'topic, route and mode links are included');
assert(learnerCss.includes('overflow-wrap:break-word;word-break:normal'));
assert(!learnerCss.includes('overflow-wrap:anywhere'));
assert(read('ui.css').includes('min-width:44px;padding:0 8px;flex-shrink:0'),'teacher language control is at least 44px wide');
assert(read('learn.js').includes('aria-label="${E(name)}"'),'lesson links expose an accessible name');
console.log('release fix gates passed');
