// Small navigation manifest: no question or answer payloads are loaded by the hub.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const grades=[1,2,3,4].map(grade=>{
  const bank=require(path.join(root,`p${grade}-skill-data.js`));
  return {grade,units:bank.units,skills:bank.skills};
});
fs.writeFileSync(path.join(root,'skill-directory.js'),'/* Generated by tools/build-skill-directory.cjs. */\nwindow.MathQuizSkillDirectory = '+JSON.stringify(grades)+';\n');
console.log('Generated directory:',grades.map(g=>`P${g.grade}: ${Object.keys(g.skills).length}`).join(', '));
